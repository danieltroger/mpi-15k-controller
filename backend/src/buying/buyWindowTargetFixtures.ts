export type LoggedBuyWindowTarget = { atMs: number; amps: number };

/** The wished-for amps over the window, in ms since its first entry */
export function parseBuyWindowTargets(fixture: { date: string; targets: string }): LoggedBuyWindowTarget[] {
  const entries = fixture.targets.split(/\s+/).filter(entry => entry.length > 0);
  const parsed = entries.map(entry => {
    const [timeOfDay, amps] = entry.split("=");
    const atMs = Date.parse(`${fixture.date}T${timeOfDay}Z`);
    if (!Number.isFinite(atMs) || amps === undefined || !Number.isFinite(Number(amps))) {
      throw new Error(`Unparseable buy-window target entry: ${entry}`);
    }
    return { atMs, amps: Number(amps) };
  });
  const windowStartMs = parsed[0]?.atMs ?? 0;
  return parsed.map(({ atMs, amps }) => ({ atMs: atMs - windowStartMs, amps }));
}
